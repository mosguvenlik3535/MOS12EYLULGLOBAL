const LANGS = ['tr', 'en', 'de'];
const DEFAULT_LANG = 'tr';

function detectLang() {
  try {
    const saved = localStorage.getItem('mos_lang');
    if (saved && LANGS.includes(saved)) return saved;
  } catch { /* yoksay */ }
  const nav = (navigator.language || DEFAULT_LANG).slice(0, 2).toLowerCase();
  return LANGS.includes(nav) ? nav : DEFAULT_LANG;
}

/** Tüm data-i18n alanlarını seçili dile göre doldurur. */
function applyLang(lang) {
  const dict = T[lang] || T[DEFAULT_LANG];
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = dict[key];
    if (val === undefined) return;
    if (el.tagName === 'META') el.setAttribute('content', val);
    else if (el.tagName === 'TITLE') el.textContent = val;
    else el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    const spec = el.getAttribute('data-i18n-attr'); // "placeholder:hero.cta1"
    const [attr, key] = spec.split(':');
    const val = dict[key];
    if (attr && key && val !== undefined) el.setAttribute(attr, val);
  });
  document.querySelectorAll('.lang button').forEach((b) => {
    b.classList.toggle('on', b.dataset.lang === lang);
  });
  try { localStorage.setItem('mos_lang', lang); } catch { /* yoksay */ }
}

document.addEventListener('DOMContentLoaded', () => {
  applyLang(detectLang());
  document.querySelectorAll('.lang button').forEach((b) => {
    b.addEventListener('click', () => applyLang(b.dataset.lang));
  });
});
