const basePhrases = (): PhraseMap => ({ ...PHRASES_A, ...PHRASES_B });

export const PHRASES: PhraseMap = (() => {
  const out = basePhrases();
  for (const lang of ['es', 'de', 'fr', 'it'] as const) {
    for (const [key, val] of Object.entries(EXTRA_LANG_MAPS[lang])) {
      const cur = out[key] ?? { en: '' };
      (cur as Record<string, string>)[lang] = val;
      out[key] = cur;
    }
  }
  return out;
})();

